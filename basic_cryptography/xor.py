def xor(ciphertext, key):
    keyy = copy.deepcopy(key)
    while len(keyy) <= len(ciphertext):
        keyy += key
    if len(keyy) != len(ciphertext):
        keyy = keyy[:len(ciphertext)]

    result = ''
    for i in range(len(ciphertext)):
        result += str(int(ciphertext[i] != keyy[i]))

    return result


